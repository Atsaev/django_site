class Command(BaseCommand):
    help = "Заполняет флешкарты стартовыми наборами карточек по темам (идемпотентно)"

    def handle(self, *args, **options):
        total_cards = 0
        for slug, (name, desc, order), cards in TOPICS:
            Topic.objects.filter(slug=slug).delete()
            topic = Topic.objects.create(
                name=name, slug=slug, description=desc, order=order
            )
            for question, answer in cards:
                Card.objects.create(topic=topic, question=question, answer=answer)
                total_cards += 1
        self.stdout.write(
            self.style.SUCCESS(
                f"Флешкарты заполнены: {len(TOPICS)} тем, {total_cards} карточек."
            )
        )
